-- Application RBAC roles for Laravel authentication identity users.
-- PostgreSQL 18. Apply ONLY to calibration_staging_db when authorized.
--
-- NOT IDEMPOTENT. Run exactly once.
-- Creates public.roles and public.user_roles.
-- Seeds Administrator, Engineer, Viewer.
-- Does not INSERT user_roles memberships.
-- Does not ALTER public.app_user or public.user_app_user_map.
--
-- Do not execute on calibration_db.
-- Do not run via php artisan migrate against staging.

BEGIN;

DO $guard$
BEGIN
    IF current_database() IS DISTINCT FROM 'calibration_staging_db' THEN
        RAISE EXCEPTION
            'refusing roles.sql: current_database()=%',
            current_database()
            USING ERRCODE = '42501';
    END IF;

    IF to_regclass('public.users') IS NULL THEN
        RAISE EXCEPTION
            'roles.sql requires public.users'
            USING ERRCODE = '42P01';
    END IF;

    IF to_regclass('public.roles') IS NOT NULL OR to_regclass('public.user_roles') IS NOT NULL THEN
        RAISE EXCEPTION
            'roles.sql is not idempotent and role tables already exist'
            USING ERRCODE = '42710';
    END IF;
END;
$guard$;

CREATE TABLE public.roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(50) NOT NULL,
    created_at timestamp(0) without time zone,
    updated_at timestamp(0) without time zone,
    CONSTRAINT uq_roles_name UNIQUE (name)
);

CREATE TABLE public.user_roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laravel_user_id bigint NOT NULL,
    role_id bigint NOT NULL,
    created_at timestamp(0) without time zone,
    updated_at timestamp(0) without time zone,
    CONSTRAINT uq_user_roles_laravel_user UNIQUE (laravel_user_id),
    CONSTRAINT uq_user_roles_user_role UNIQUE (laravel_user_id, role_id),
    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (laravel_user_id)
        REFERENCES public.users (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (role_id)
        REFERENCES public.roles (id)
        ON DELETE RESTRICT
);

INSERT INTO public.roles (name, created_at, updated_at)
VALUES
    ('Administrator', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP),
    ('Engineer', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP),
    ('Viewer', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);

COMMENT ON TABLE public.roles IS
$$Trusted application role catalog for Laravel users.id. Not domain app_user roles.$$;

COMMENT ON TABLE public.user_roles IS
$$Exactly one application role membership per Laravel user. Fail closed when missing.$$;

COMMIT;
