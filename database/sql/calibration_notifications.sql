-- Persistent per-user calibration notifications.
-- Apply ONLY to calibration_staging_db after explicit approval.
--
-- NOT IDEMPOTENT. This artifact is intentionally outside database/migrations.
-- Do not execute on calibration_db.

BEGIN;

DO $guard$
BEGIN
    IF current_database() IS DISTINCT FROM 'calibration_staging_db' THEN
        RAISE EXCEPTION
            'refusing calibration_notifications.sql: current_database()=%',
            current_database()
            USING ERRCODE = '42501';
    END IF;

    IF to_regclass('public.users') IS NULL
       OR to_regclass('public.instrument') IS NULL
       OR to_regclass('public.instrument_type') IS NULL
       OR to_regclass('public.calibration') IS NULL THEN
        RAISE EXCEPTION
            'calibration_notifications.sql requires users, instrument, instrument_type, and calibration'
            USING ERRCODE = '42P01';
    END IF;

    IF to_regclass('public.calibration_notifications') IS NOT NULL THEN
        RAISE EXCEPTION
            'calibration_notifications.sql is not idempotent and the table already exists'
            USING ERRCODE = '42710';
    END IF;
END;
$guard$;

CREATE TABLE public.calibration_notifications (
    calibration_notification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id bigint NOT NULL,
    instrument_id bigint,
    instrument_type_id bigint,
    source_calibration_id bigint,
    event_type character varying(32) NOT NULL,
    event_key character varying(512) NOT NULL,
    occurrence_revision smallint NOT NULL DEFAULT 1,
    instrument_name_snapshot text NOT NULL,
    instrument_type_snapshot text NOT NULL,
    serial_number_snapshot text,
    due_date_snapshot date NOT NULL,
    read_at timestamp(0) with time zone,
    resolved_at timestamp(0) with time zone,
    resolution_calibration_id bigint,
    created_at timestamp(0) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(0) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_calibration_notifications_event_type
        CHECK (event_type IN ('due_soon', 'overdue')),
    CONSTRAINT chk_calibration_notifications_event_key
        CHECK (length(trim(event_key)) > 0),
    CONSTRAINT chk_calibration_notifications_occurrence_revision
        CHECK (occurrence_revision > 0),
    CONSTRAINT chk_calibration_notifications_instrument_name
        CHECK (length(trim(instrument_name_snapshot)) > 0),
    CONSTRAINT chk_calibration_notifications_type_name
        CHECK (length(trim(instrument_type_snapshot)) > 0),
    CONSTRAINT uq_calibration_notifications_recipient_event
        UNIQUE (recipient_user_id, event_key, occurrence_revision),
    CONSTRAINT fk_calibration_notifications_recipient
        FOREIGN KEY (recipient_user_id)
        REFERENCES public.users (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_calibration_notifications_instrument
        FOREIGN KEY (instrument_id)
        REFERENCES public.instrument (instrument_id)
        ON DELETE SET NULL,
    CONSTRAINT fk_calibration_notifications_instrument_type
        FOREIGN KEY (instrument_type_id)
        REFERENCES public.instrument_type (instrument_type_id)
        ON DELETE SET NULL,
    CONSTRAINT fk_calibration_notifications_source_calibration
        FOREIGN KEY (source_calibration_id)
        REFERENCES public.calibration (calibration_id)
        ON DELETE SET NULL,
    CONSTRAINT fk_calibration_notifications_resolution_calibration
        FOREIGN KEY (resolution_calibration_id)
        REFERENCES public.calibration (calibration_id)
        ON DELETE SET NULL
);

CREATE INDEX ix_calibration_notifications_recipient_active_read
    ON public.calibration_notifications (recipient_user_id, resolved_at, read_at, created_at DESC);

CREATE INDEX ix_calibration_notifications_recipient_created
    ON public.calibration_notifications (recipient_user_id, created_at DESC);

CREATE INDEX ix_calibration_notifications_pair_event
    ON public.calibration_notifications (instrument_type_id, event_type, due_date_snapshot);

CREATE INDEX ix_calibration_notifications_source_calibration
    ON public.calibration_notifications (source_calibration_id);

CREATE INDEX ix_calibration_notifications_recipient_event_revision
    ON public.calibration_notifications (recipient_user_id, event_key, occurrence_revision DESC);

COMMIT;
