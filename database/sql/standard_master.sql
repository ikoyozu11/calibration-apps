-- Dedicated Standard(s) Used master. PostgreSQL 18.
-- Apply ONLY to calibration_staging_db.
--
-- NOT IDEMPOTENT. Run exactly once.
-- Does not INSERT master, assignment, instrument, or calibration rows.
-- Does not ALTER calibration_standard_usage.
--
-- Do not execute on calibration_db until staging tests pass.

BEGIN;

DO $guard$
BEGIN
    IF current_database() IS DISTINCT FROM 'calibration_staging_db' THEN
        RAISE EXCEPTION
            'refusing standard_master.sql: current_database()=%',
            current_database()
            USING ERRCODE = '42501';
    END IF;

    IF to_regclass('public.standard_master') IS NOT NULL THEN
        RAISE EXCEPTION
            'standard_master.sql is not idempotent and has already been applied'
            USING ERRCODE = '42710';
    END IF;
END;
$guard$;

CREATE TABLE public.standard_master (
    standard_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    standard_code character varying(20) NOT NULL,
    instrument_name character varying(150) NOT NULL,
    type_specification character varying(150),
    serial_number character varying(150),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_standard_master_code UNIQUE (standard_code)
);

CREATE INDEX ix_standard_master_name
    ON public.standard_master (instrument_name);

CREATE INDEX ix_standard_master_serial
    ON public.standard_master (serial_number);

COMMIT;
