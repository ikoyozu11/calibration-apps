    CONSTRAINT uq_test_point_value_cell
        UNIQUE (test_profile_id, test_point_id, test_column_id),
    CONSTRAINT fk_test_point_value_point
        FOREIGN KEY (test_profile_id, test_point_id)
        REFERENCES public.test_point (test_profile_id, test_point_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_test_point_value_column
        FOREIGN KEY (test_profile_id, test_column_id)
        REFERENCES public.test_column (test_profile_id, test_column_id)
