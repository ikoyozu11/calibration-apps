CREATE FUNCTION public.trg_test_point_value_type_check()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
DECLARE
    source record;
BEGIN
    IF TG_OP <> 'INSERT' AND TG_OP <> 'UPDATE' THEN
        RAISE EXCEPTION 'template value check called for %', TG_OP
            USING ERRCODE = '0A000';
    END IF;

    SELECT data_type, value_source
    INTO source
    FROM public.test_column
    WHERE test_profile_id = NEW.test_profile_id
      AND test_column_id = NEW.test_column_id;

    IF NOT FOUND THEN
        RETURN NEW;
    END IF;

    IF source.value_source <> 'template' THEN
        RAISE EXCEPTION 'only template columns can store template values'
            USING ERRCODE = '23514', CONSTRAINT = 'test_point_value_template_only';
    END IF;

    IF source.data_type IN ('numeric', 'duration') AND NEW.text_value IS NOT NULL THEN
        RAISE EXCEPTION 'numeric column cannot store text_value'
            USING ERRCODE = '23514', CONSTRAINT = 'test_point_value_numeric_type';
    END IF;

    IF source.data_type = 'text' AND NEW.numeric_value IS NOT NULL THEN
        RAISE EXCEPTION 'text column cannot store numeric_value'
            USING ERRCODE = '23514', CONSTRAINT = 'test_point_value_text_type';
    END IF;

    IF source.data_type = 'duration'
       AND NEW.numeric_value IS NOT NULL
       AND NEW.numeric_value <> trunc(NEW.numeric_value) THEN
        RAISE EXCEPTION 'duration column must store whole seconds'
            USING ERRCODE = '23514', CONSTRAINT = 'test_point_value_duration_type';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_test_point_value_type_check
BEFORE INSERT OR UPDATE
ON public.test_point_value
FOR EACH ROW
EXECUTE FUNCTION public.trg_test_point_value_type_check();

CREATE FUNCTION public.test_column_insert(
    p_test_profile_id bigint,
    p_column_key varchar,
    p_column_label varchar,
    p_column_order integer,
    p_data_type text,
    p_value_source text,
    p_unit varchar DEFAULT NULL,
    p_display_scale smallint DEFAULT NULL,
    p_formula_code text DEFAULT NULL,
    p_formula_inputs text[] DEFAULT ARRAY[]::text[]
)
RETURNS bigint
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
DECLARE
    new_id bigint;
BEGIN
    PERFORM 1
    FROM public.test_profile
    WHERE test_profile_id = p_test_profile_id
    FOR NO KEY UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'test profile % does not exist', p_test_profile_id
            USING ERRCODE = '23503', CONSTRAINT = 'fk_test_column_test_profile';
    END IF;

    INSERT INTO public.test_column (
        test_profile_id, column_key, column_label, column_order,
        data_type, value_source, unit, display_scale, formula_code, formula_inputs
    )
    VALUES (
        p_test_profile_id, p_column_key, p_column_label, p_column_order,
        p_data_type, p_value_source, p_unit, p_display_scale, p_formula_code,
        COALESCE(p_formula_inputs, ARRAY[]::text[])
    )
    RETURNING test_column_id INTO new_id;

    RETURN new_id;
END;
$$;

