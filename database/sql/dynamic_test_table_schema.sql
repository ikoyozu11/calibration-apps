    p_formula_code text DEFAULT NULL,
    p_formula_inputs text[] DEFAULT ARRAY[]::text[]
)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
DECLARE
    profile_id bigint;
BEGIN
    SELECT test_profile_id
    INTO profile_id
    FROM public.test_column
    WHERE test_column_id = p_test_column_id;

