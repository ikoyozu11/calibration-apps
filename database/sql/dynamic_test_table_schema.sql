        CHECK (text_value IS NULL OR length(btrim(text_value)) > 0),
    CONSTRAINT ck_test_point_value_unit
        CHECK (unit IS NULL OR length(btrim(unit)) > 0),
    CONSTRAINT ck_test_point_value_one_kind
        CHECK (numeric_value IS NULL OR text_value IS NULL)
);

