CREATE FUNCTION public.test_column_reorder(
    p_test_profile_id bigint,
    p_column_ids bigint[]
)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
DECLARE
    v_updated_count integer;
BEGIN
    PERFORM 1
    FROM public.test_profile
    WHERE test_profile_id = p_test_profile_id
    FOR NO KEY UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'test profile % does not exist', p_test_profile_id
            USING ERRCODE = '23503', CONSTRAINT = 'fk_test_column_test_profile';
    END IF;

    IF p_column_ids IS NULL
       OR cardinality(p_column_ids) = 0
       OR cardinality(p_column_ids) <> (
            SELECT count(DISTINCT id)
            FROM unnest(p_column_ids) AS id
       )
       OR EXISTS (
            SELECT 1
            FROM unnest(p_column_ids) AS id
            WHERE id IS NULL
       )
       OR cardinality(p_column_ids) <> (
            SELECT count(*)
            FROM public.test_column
            WHERE test_profile_id = p_test_profile_id
       )
       OR EXISTS (
            SELECT 1
            FROM unnest(p_column_ids) AS id
            WHERE NOT EXISTS (
                SELECT 1
                FROM public.test_column AS column_row
                WHERE column_row.test_column_id = id
                  AND column_row.test_profile_id = p_test_profile_id
            )
       ) THEN
        RAISE EXCEPTION 'column reorder must list every column of the profile once'
            USING ERRCODE = '23514', CONSTRAINT = 'test_column_reorder';
    END IF;

    UPDATE public.test_column AS column_row
    SET column_order = ordered.column_order::integer
    FROM unnest(p_column_ids) WITH ORDINALITY AS ordered(test_column_id, column_order)
    WHERE column_row.test_column_id = ordered.test_column_id
      AND column_row.test_profile_id = p_test_profile_id;

    GET DIAGNOSTICS v_updated_count = ROW_COUNT;

    IF v_updated_count <> cardinality(p_column_ids) THEN
        RAISE EXCEPTION 'column reorder did not update every column'
            USING ERRCODE = '23514', CONSTRAINT = 'test_column_reorder';
    END IF;
END;
$$;

CREATE FUNCTION public.test_point_value_upsert(
    p_test_profile_id bigint,
    p_test_point_id bigint,
    p_test_column_id bigint,
    p_numeric_value numeric DEFAULT NULL,
    p_text_value text DEFAULT NULL,
    p_unit varchar DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    PERFORM 1
    FROM public.test_profile
    WHERE test_profile_id = p_test_profile_id
    FOR SHARE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'test profile % does not exist', p_test_profile_id
            USING ERRCODE = '23503', CONSTRAINT = 'fk_test_point_value_column';
    END IF;

    INSERT INTO public.test_point_value (
        test_profile_id, test_point_id, test_column_id,
        numeric_value, text_value, unit
    )
    VALUES (
        p_test_profile_id, p_test_point_id, p_test_column_id,
        p_numeric_value, p_text_value, p_unit
    )
    ON CONFLICT ON CONSTRAINT uq_test_point_value_cell
    DO UPDATE SET
        numeric_value = EXCLUDED.numeric_value,
        text_value = EXCLUDED.text_value,
        unit = EXCLUDED.unit;
END;
$$;

