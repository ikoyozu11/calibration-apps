CREATE FUNCTION public.test_column_formula_inputs_wellformed(
    column_key text,
    formula_inputs text[]
)
RETURNS boolean
LANGUAGE plpgsql
IMMUTABLE
PARALLEL SAFE
SET search_path = pg_catalog
AS $$
DECLARE
    input_key text;
    seen text[] := ARRAY[]::text[];
BEGIN
    IF column_key IS NULL OR formula_inputs IS NULL THEN
        RETURN false;
    END IF;

    FOREACH input_key IN ARRAY formula_inputs LOOP
        IF input_key IS NULL
           OR input_key = column_key
           OR input_key = ANY (seen) THEN
            RETURN false;
        END IF;

        seen := seen || input_key;
    END LOOP;

    RETURN true;
END;
$$;

