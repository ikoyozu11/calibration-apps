CREATE TABLE public.test_column (
    test_column_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_profile_id bigint NOT NULL,
    column_key varchar(63) NOT NULL,
    column_label varchar(255) NOT NULL,
    column_order integer NOT NULL,
    data_type text NOT NULL,
    value_source text NOT NULL,
    unit varchar(50),
    display_scale smallint,
    formula_code text,
    formula_inputs text[] NOT NULL DEFAULT ARRAY[]::text[],
    created_at timestamp without time zone NOT NULL DEFAULT now(),
    CONSTRAINT uq_test_column_profile_identity
        UNIQUE (test_profile_id, test_column_id),
    CONSTRAINT uq_test_column_key
        UNIQUE (test_profile_id, column_key),
    CONSTRAINT uq_test_column_order
        UNIQUE (test_profile_id, column_order)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_test_column_test_profile
        FOREIGN KEY (test_profile_id)
        REFERENCES public.test_profile (test_profile_id)
        ON DELETE CASCADE,
    CONSTRAINT ck_test_column_key
        CHECK (column_key ~ '^[a-z][a-z0-9_]{0,62}$'),
    CONSTRAINT ck_test_column_label
        CHECK (length(btrim(column_label)) > 0),
    CONSTRAINT ck_test_column_order
        CHECK (column_order >= 1),
    CONSTRAINT ck_test_column_data_type
        CHECK (data_type IN ('numeric', 'text', 'duration')),
    CONSTRAINT ck_test_column_value_source
        CHECK (value_source IN ('template', 'engineer', 'calculated')),
    CONSTRAINT ck_test_column_scale
        CHECK (
            display_scale IS NULL
            OR (data_type = 'numeric' AND display_scale BETWEEN 0 AND 6)
        ),
    CONSTRAINT ck_test_column_formula
        CHECK (
            (
                value_source = 'calculated'
                AND formula_code IS NOT NULL
                AND (
                    (
                        data_type = 'numeric'
                        AND (
                            (formula_code = 'average' AND cardinality(formula_inputs) >= 1)
                            OR (formula_code IN ('deviation', 'standard_minus_reading', 'reading_minus_standard') AND cardinality(formula_inputs) = 2)
                        )
                    )
                    OR (
                        data_type = 'duration'
                        AND formula_code IN ('deviation', 'standard_minus_reading', 'reading_minus_standard')
                        AND cardinality(formula_inputs) = 2
                    )
                )
            )
            OR (
                value_source IN ('template', 'engineer')
                AND formula_code IS NULL
                AND cardinality(formula_inputs) = 0
            )
        ),
    CONSTRAINT ck_test_column_formula_inputs
        CHECK (public.test_column_formula_inputs_wellformed(column_key, formula_inputs))
);

