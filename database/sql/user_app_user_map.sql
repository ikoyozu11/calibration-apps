-- One-to-one map from Laravel users.id to domain app_user.app_user_id.
-- PostgreSQL 18. Apply ONLY to calibration_staging_db.
--
-- NOT IDEMPOTENT. Run exactly once.
-- Does not INSERT rows.
-- Does not ALTER public.users or public.app_user.
-- Does not change authentication or existing actor foreign keys.
--
-- Offline key evidence from the 2026-10-20 custom dump table definitions:
--   public.users.id bigint NOT NULL
--   users_pkey PRIMARY KEY (id)
--   public.app_user.app_user_id bigint NOT NULL
--   app_user_pkey PRIMARY KEY (app_user_id)
-- The type gate below aborts if staging information_schema disagrees.
--
-- Do not execute on calibration_db.

BEGIN;

DO $guard$
DECLARE
    users_id_type text;
    app_user_id_type text;
BEGIN
    IF current_database() IS DISTINCT FROM 'calibration_staging_db' THEN
        RAISE EXCEPTION
            'refusing user_app_user_map.sql: current_database()=%',
            current_database()
            USING ERRCODE = '42501';
    END IF;

    IF to_regclass('public.user_app_user_map') IS NOT NULL THEN
        RAISE EXCEPTION
            'user_app_user_map.sql is not idempotent and has already been applied'
            USING ERRCODE = '42710';
    END IF;

    IF to_regclass('public.users') IS NULL OR to_regclass('public.app_user') IS NULL THEN
        RAISE EXCEPTION
            'user_app_user_map.sql requires public.users and public.app_user'
            USING ERRCODE = '42P01';
    END IF;

    SELECT data_type
    INTO users_id_type
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'users'
      AND column_name = 'id';

    SELECT data_type
    INTO app_user_id_type
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'app_user'
      AND column_name = 'app_user_id';

    IF users_id_type IS DISTINCT FROM 'bigint'
       OR app_user_id_type IS DISTINCT FROM 'bigint' THEN
        RAISE EXCEPTION
            'refusing user_app_user_map.sql: users.id type is %, app_user.app_user_id type is %; both must be bigint',
            COALESCE(users_id_type, 'missing'),
            COALESCE(app_user_id_type, 'missing')
            USING ERRCODE = '42804';
    END IF;
END;
$guard$;

CREATE TABLE public.user_app_user_map (
    user_app_user_map_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laravel_user_id bigint NOT NULL,
    app_user_id bigint NOT NULL,
    status character varying(20) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    inactivated_at timestamp with time zone,
    CONSTRAINT uq_user_app_user_map_laravel_user UNIQUE (laravel_user_id),
    CONSTRAINT uq_user_app_user_map_app_user UNIQUE (app_user_id),
    CONSTRAINT fk_user_app_user_map_user
        FOREIGN KEY (laravel_user_id)
        REFERENCES public.users (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_user_app_user_map_app_user
        FOREIGN KEY (app_user_id)
        REFERENCES public.app_user (app_user_id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_user_app_user_map_status
        CHECK (status IN ('active', 'inactive')),
    CONSTRAINT chk_user_app_user_map_inactivated_at
        CHECK (
            (status = 'active' AND inactivated_at IS NULL)
            OR (status = 'inactive' AND inactivated_at IS NOT NULL)
        )
);

COMMENT ON TABLE public.user_app_user_map IS
$$Explicit one-to-one link between Laravel users.id and app_user.app_user_id.
Inactive rows stay in place and keep both unique keys. Actor history stores
app_user_id on the session row and does not follow this map.$$;

COMMIT;
