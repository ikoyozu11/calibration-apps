-- Dedicated Calibration Activity master. PostgreSQL 18.
-- Apply ONLY to calibration_staging_db.
--
-- NOT IDEMPOTENT. Run exactly once.
-- Does not INSERT master or calibration_activity rows.
-- Does not ALTER calibration_activity.
--
-- Do not execute on calibration_db until staging tests pass.

BEGIN;

DO $guard$
BEGIN
    IF current_database() IS DISTINCT FROM 'calibration_staging_db' THEN
        RAISE EXCEPTION
            'refusing calibration_activity_master.sql: current_database()=%',
            current_database()
            USING ERRCODE = '42501';
    END IF;

    IF to_regclass('public.calibration_activity_master') IS NOT NULL THEN
        RAISE EXCEPTION
            'calibration_activity_master.sql is not idempotent and has already been applied'
            USING ERRCODE = '42710';
    END IF;
END;
$guard$;

CREATE TABLE public.calibration_activity_master (
    activity_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_code character varying(30) NOT NULL,
    activity_name character varying(255) NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_calibration_activity_master_code UNIQUE (activity_code),
    CONSTRAINT chk_calibration_activity_master_code
        CHECK (length(btrim(activity_code)) > 0),
    CONSTRAINT chk_calibration_activity_master_name
        CHECK (length(btrim(activity_name)) > 0)
);

CREATE INDEX ix_calibration_activity_master_name
    ON public.calibration_activity_master (activity_name);

CREATE INDEX ix_calibration_activity_master_active
    ON public.calibration_activity_master (is_active);

COMMENT ON TABLE public.calibration_activity_master IS
$$Global Calibration Activity catalog. Future Calibration Session CRUD should
copy activity_name onto calibration_activity at selection time and later add a
nullable activity_id FK. Do not live-join this table for completed certificates.$$;

COMMIT;
