-- Calibration Due notification history (Phase 3B candidate artifact).
-- PostgreSQL 18. Apply ONLY to calibration_staging_db after explicit approval.
--
-- NOT IDEMPOTENT. Run exactly once after the existing instrument, type, and
-- calibration domain tables are present. This artifact is intentionally not
-- in the current approved atomic deployment package yet.
--
-- Do not execute on calibration_db.
-- Do not run via php artisan migrate against staging or production.

BEGIN;

DO $guard$
BEGIN
    IF current_database() IS DISTINCT FROM 'calibration_staging_db' THEN
        RAISE EXCEPTION
            'refusing calibration_due_notification_history.sql: current_database()=%',
            current_database()
            USING ERRCODE = '42501';
    END IF;

    IF to_regclass('public.instrument') IS NULL
       OR to_regclass('public.instrument_type') IS NULL
       OR to_regclass('public.calibration') IS NULL THEN
        RAISE EXCEPTION
            'calibration_due_notification_history.sql requires instrument, instrument_type, and calibration'
            USING ERRCODE = '42P01';
    END IF;

    IF to_regclass('public.calibration_due_notification_batches') IS NOT NULL
       OR to_regclass('public.calibration_due_notification_items') IS NOT NULL THEN
        RAISE EXCEPTION
            'calibration_due_notification_history.sql is not idempotent and notification tables already exist'
            USING ERRCODE = '42710';
    END IF;
END;
$guard$;

CREATE TABLE public.calibration_due_notification_batches (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_date date NOT NULL,
    timezone character varying(64) NOT NULL,
    recipient character varying(320) NOT NULL,
    status character varying(32) NOT NULL,
    attempts smallint NOT NULL DEFAULT 0,
    claimed_at timestamp(0) with time zone,
    sent_at timestamp(0) with time zone,
    failed_at timestamp(0) with time zone,
    failure_message text,
    created_at timestamp(0) with time zone,
    updated_at timestamp(0) with time zone,
    CONSTRAINT uq_calibration_due_notification_batch_day_recipient
        UNIQUE (notification_date, recipient)
);

CREATE INDEX ix_calibration_due_notification_batches_status_date
    ON public.calibration_due_notification_batches (status, notification_date);

CREATE TABLE public.calibration_due_notification_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id bigint NOT NULL,
    instrument_id bigint NOT NULL,
    instrument_type_id bigint NOT NULL,
    latest_calibration_id bigint NOT NULL,
    calibration_method character varying(32) NOT NULL,
    instrument_name_snapshot text NOT NULL,
    instrument_type_snapshot text NOT NULL,
    serial_number_snapshot text,
    location_snapshot text,
    due_date_snapshot date NOT NULL,
    milestone_code character varying(32) NOT NULL,
    milestone_date date NOT NULL,
    recipient character varying(320) NOT NULL,
    status character varying(32) NOT NULL,
    attempts smallint NOT NULL DEFAULT 0,
    last_attempt_at timestamp(0) with time zone,
    failure_message text,
    created_at timestamp(0) with time zone,
    updated_at timestamp(0) with time zone,
    CONSTRAINT fk_calibration_due_notification_item_batch
        FOREIGN KEY (batch_id)
        REFERENCES public.calibration_due_notification_batches (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_calibration_due_notification_item_instrument
        FOREIGN KEY (instrument_id)
        REFERENCES public.instrument (instrument_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_calibration_due_notification_item_type
        FOREIGN KEY (instrument_type_id)
        REFERENCES public.instrument_type (instrument_type_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_calibration_due_notification_item_calibration
        FOREIGN KEY (latest_calibration_id)
        REFERENCES public.calibration (calibration_id)
        ON DELETE RESTRICT,
    CONSTRAINT uq_calibration_due_notification_item_identity
        UNIQUE (instrument_type_id, due_date_snapshot, milestone_code, recipient)
);

CREATE INDEX ix_calibration_due_notification_items_batch_status
    ON public.calibration_due_notification_items (batch_id, status);

CREATE INDEX ix_calibration_due_notification_items_milestone_status
    ON public.calibration_due_notification_items (milestone_date, status);

COMMIT;
