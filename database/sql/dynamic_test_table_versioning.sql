CREATE FUNCTION public.test_profile_version_fork(p_source_version_id bigint)
RETURNS bigint
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
DECLARE
    source public.test_profile_version%ROWTYPE;
    new_id bigint;
    next_number integer;
    old_column record;
    new_column_id bigint;
    column_map jsonb := '{}'::jsonb;
    old_point record;
    new_point_id bigint;
    point_map jsonb := '{}'::jsonb;
    old_cell record;
BEGIN
    SELECT *
    INTO source
    FROM public.test_profile_version
    WHERE test_profile_version_id = p_source_version_id
    FOR SHARE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'test profile version % does not exist', p_source_version_id
            USING ERRCODE = '23503', CONSTRAINT = 'fk_test_column_version_profile';
    END IF;

    IF source.status = 'draft' THEN
        RAISE EXCEPTION 'fork a published version, not a draft'
            USING ERRCODE = '23514', CONSTRAINT = 'test_profile_version_status';
    END IF;

    PERFORM 1
    FROM public.test_profile
    WHERE test_profile_id = source.test_profile_id
    FOR UPDATE;

    IF EXISTS (
        SELECT 1
        FROM public.test_profile_version
        WHERE test_profile_id = source.test_profile_id
          AND status = 'draft'
    ) THEN
        RAISE EXCEPTION 'a draft version already exists for this test table'
            USING ERRCODE = '23514', CONSTRAINT = 'uq_test_profile_version_draft';
    END IF;

    SELECT max(version_number) + 1
    INTO next_number
    FROM public.test_profile_version
    WHERE test_profile_id = source.test_profile_id;

    INSERT INTO public.test_profile_version (
        test_profile_id, version_number, status,
        profile_name, display_title, description, published_at
    )
    VALUES (
        source.test_profile_id, next_number, 'draft',
        source.profile_name, source.display_title, source.description, NULL
    )
    RETURNING test_profile_version_id INTO new_id;

    FOR old_column IN
        SELECT *
        FROM public.test_column
        WHERE test_profile_version_id = source.test_profile_version_id
        ORDER BY CASE WHEN value_source = 'calculated' THEN 1 ELSE 0 END, column_order, test_column_id
    LOOP
        INSERT INTO public.test_column (
            test_profile_id, test_profile_version_id, column_key, column_label, column_order,
            data_type, value_source, unit, display_scale, formula_code, formula_inputs
        )
        VALUES (
            old_column.test_profile_id, new_id, old_column.column_key, old_column.column_label,
            old_column.column_order, old_column.data_type, old_column.value_source, old_column.unit,
            old_column.display_scale, old_column.formula_code, old_column.formula_inputs
        )
        RETURNING test_column_id INTO new_column_id;

        column_map := column_map || jsonb_build_object(old_column.test_column_id::text, new_column_id);
    END LOOP;

    FOR old_point IN
        SELECT *
        FROM public.test_point
        WHERE test_profile_version_id = source.test_profile_version_id
        ORDER BY point_order, test_point_id
    LOOP
        INSERT INTO public.test_point (
            test_profile_id, test_profile_version_id, point_order, nominal_value, unit,
            tolerance_plus, tolerance_minus, description
        )
        VALUES (
            old_point.test_profile_id, new_id, old_point.point_order, old_point.nominal_value,
            old_point.unit, old_point.tolerance_plus, old_point.tolerance_minus, old_point.description
        )
        RETURNING test_point_id INTO new_point_id;

        point_map := point_map || jsonb_build_object(old_point.test_point_id::text, new_point_id);
    END LOOP;

    FOR old_cell IN
        SELECT *
        FROM public.test_point_value
        WHERE test_profile_version_id = source.test_profile_version_id
        ORDER BY test_point_value_id
    LOOP
        INSERT INTO public.test_point_value (
            test_profile_id, test_profile_version_id, test_point_id, test_column_id,
            numeric_value, text_value, unit
        )
        VALUES (
            old_cell.test_profile_id,
            new_id,
            (point_map ->> old_cell.test_point_id::text)::bigint,
            (column_map ->> old_cell.test_column_id::text)::bigint,
            old_cell.numeric_value,
            old_cell.text_value,
            old_cell.unit
        );
    END LOOP;

    RETURN new_id;
END;
$$;

CREATE FUNCTION public.test_profile_version_publish(p_test_profile_id bigint)
RETURNS bigint
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
DECLARE
    draft_id bigint;
    active_id bigint;
BEGIN
    PERFORM 1
    FROM public.test_profile
    WHERE test_profile_id = p_test_profile_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'test profile % does not exist', p_test_profile_id
            USING ERRCODE = '23503', CONSTRAINT = 'fk_test_profile_version_profile';
    END IF;

    SELECT test_profile_version_id
    INTO draft_id
    FROM public.test_profile_version
    WHERE test_profile_id = p_test_profile_id
      AND status = 'draft'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'test table has no draft version to publish'
            USING ERRCODE = '23514', CONSTRAINT = 'test_profile_version_status';
    END IF;

    SELECT test_profile_version_id
    INTO active_id
    FROM public.test_profile_version
    WHERE test_profile_id = p_test_profile_id
      AND status = 'active'
    FOR UPDATE;

    IF active_id IS NOT NULL THEN
        UPDATE public.test_profile_version
        SET status = 'retired'
        WHERE test_profile_version_id = active_id;
    END IF;

    UPDATE public.test_profile_version
    SET status = 'active',
        published_at = now()
    WHERE test_profile_version_id = draft_id;

    UPDATE public.test_profile AS profile_row
    SET profile_name = version_row.profile_name,
        display_title = version_row.display_title,
        description = version_row.description
    FROM public.test_profile_version AS version_row
    WHERE profile_row.test_profile_id = p_test_profile_id
      AND version_row.test_profile_version_id = draft_id;

    RETURN draft_id;
END;
$$;

CREATE FUNCTION public.test_profile_delete_unused(p_test_profile_id bigint)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    IF public.test_profile_is_used_in_calibration(p_test_profile_id)
       OR EXISTS (
            SELECT 1
            FROM public.calibration_scope
            WHERE test_profile_version_id IN (
                SELECT test_profile_version_id
                FROM public.test_profile_version
                WHERE test_profile_id = p_test_profile_id
            )
       ) THEN
        RAISE EXCEPTION 'this test table is used by a calibration and cannot be deleted'
            USING ERRCODE = '23503', CONSTRAINT = 'fk_calibration_scope_test_profile';
    END IF;

    DELETE FROM public.test_profile
    WHERE test_profile_id = p_test_profile_id;
END;
$$;

COMMENT ON FUNCTION public.test_profile_delete_unused(bigint) IS
$$Physically deletes an unused Test Table and its versions. Does not use a
session GUC. Published rows may be deleted only when no calibration_scope or
calibration_test_result references that table.

This does not protect against instrument_type ON DELETE CASCADE, which still
removes test_profile rows (and therefore versions) when an instrument type is
deleted. Do not change that foreign key without a separate approval.
$$;

CREATE FUNCTION public.test_profile_archive(p_test_profile_id bigint)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    UPDATE public.test_profile
    SET archived_at = COALESCE(archived_at, now())
    WHERE test_profile_id = p_test_profile_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'test profile % does not exist', p_test_profile_id
            USING ERRCODE = '23503', CONSTRAINT = 'fk_test_profile_version_profile';
    END IF;
END;
$$;

-- ---------------------------------------------------------------------------
-- 8. Post-condition checks (still no calibration mutation)
-- ---------------------------------------------------------------------------

DO $final_guard$
DECLARE
    unexpected integer;
    original_points integer;
    current_points integer;
BEGIN
    SELECT count(*) INTO unexpected
    FROM public.calibration_scope
    WHERE test_profile_version_id IS NOT NULL
       OR test_table_snapshot IS NOT NULL;

    IF unexpected <> 0 THEN
        RAISE EXCEPTION 'legacy calibration_scope snapshot columns must remain null; found % unexpected row(s)', unexpected;
    END IF;

    SELECT count(*) INTO unexpected
    FROM public.calibration_result_value;

    IF unexpected <> 0 THEN
        RAISE EXCEPTION 'calibration_result_value must start empty; found % row(s)', unexpected;
    END IF;

    SELECT count(*) INTO unexpected
    FROM public.test_column AS column_row
    JOIN public.test_profile_version AS version_row
      ON version_row.test_profile_version_id = column_row.test_profile_version_id
    WHERE version_row.test_profile_id IS DISTINCT FROM column_row.test_profile_id;

    IF unexpected <> 0 THEN
        RAISE EXCEPTION 'test_column version/profile mismatch on % row(s)', unexpected;
    END IF;

    SELECT count(DISTINCT result_row.test_point_id) INTO original_points
    FROM public.calibration_test_result AS result_row;

    SELECT count(DISTINCT result_row.test_point_id) INTO current_points
    FROM public.calibration_test_result AS result_row
    JOIN public.test_point AS point_row
      ON point_row.test_point_id = result_row.test_point_id;

    IF original_points IS DISTINCT FROM current_points THEN
        RAISE EXCEPTION 'historical test_point_id references were broken during versioning';
    END IF;

    SELECT count(*) INTO unexpected
    FROM public.test_profile AS profile_row
    JOIN public.test_profile_version AS version_row
      ON version_row.test_profile_id = profile_row.test_profile_id
     AND version_row.version_number = 1
    WHERE NOT public.test_profile_is_used_in_calibration(profile_row.test_profile_id)
      AND (version_row.status IS DISTINCT FROM 'draft' OR version_row.published_at IS NOT NULL);

    IF unexpected <> 0 THEN
        RAISE EXCEPTION 'unused test_profile rows must backfill as unpublished draft; found %', unexpected;
    END IF;

    SELECT count(*) INTO unexpected
    FROM public.test_profile AS profile_row
    JOIN public.test_profile_version AS version_row
      ON version_row.test_profile_id = profile_row.test_profile_id
     AND version_row.version_number = 1
    WHERE public.test_profile_is_used_in_calibration(profile_row.test_profile_id)
      AND (version_row.status IS DISTINCT FROM 'active' OR version_row.published_at IS NULL);

    IF unexpected <> 0 THEN
        RAISE EXCEPTION 'historically used test_profile rows must backfill as active; found %', unexpected;
    END IF;
END;
$final_guard$;

COMMIT;
