-- Additive Versioning + Snapshot schema for Dynamic Test Tables (step 30G).
-- PostgreSQL 18. Run AFTER dynamic_test_table_schema.sql and dynamic_test_table_duration.sql.
--
-- NOT IDEMPOTENT. Run exactly once. Re-running raises if test_profile_version exists.
-- Do not execute on the primary database until staging tests pass.
--
-- This script:
--   * does not UPDATE calibration_scope, calibration_test_result, or certificate rows
--   * backfills Version 1 as draft when the Test Table has no calibration references
--   * backfills Version 1 as active only when calibration_scope or
--     calibration_test_result already points at the table
--   * makes published (active/retired) versions immutable; edits require fork
--   * does not change instrument_type -> test_profile ON DELETE CASCADE
--
-- Existing Livewire writers still call test_column_* / test_point_value_*
-- without a version id. They succeed only against a DRAFT version.
BEGIN;

DO $already_applied$
BEGIN
    IF to_regclass('public.test_profile_version') IS NOT NULL THEN
        RAISE EXCEPTION
            'dynamic_test_table_versioning.sql is not idempotent and has already been applied'
            USING ERRCODE = '42710';
    END IF;
END;
$already_applied$;

