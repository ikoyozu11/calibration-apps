-- Drop profile-scoped key/order uniques by actual column lists so renamed
-- production constraints (including DEFERRABLE uq_test_column_order) are removed.
-- Keep identity uniques: (test_profile_id, test_column_id) and (test_profile_id, test_point_id).
-- Keep uq_test_point_value_cell; copy-on-write uses new point/column ids.
DO $drop_profile_scoped_uniques$
DECLARE
    rec record;
    cols text[];
BEGIN
    FOR rec IN
        SELECT con.oid, con.conname, src.relname AS table_name, con.conrelid, con.conkey
        FROM pg_constraint AS con
        JOIN pg_class AS src
          ON src.oid = con.conrelid
        JOIN pg_namespace AS nsp
          ON nsp.oid = src.relnamespace
        WHERE nsp.nspname = 'public'
          AND con.contype = 'u'
          AND src.relname IN ('test_column', 'test_point')
        ORDER BY src.relname, con.conname
    LOOP
        SELECT array_agg(att.attname ORDER BY ord.ordinality)
        INTO cols
        FROM unnest(rec.conkey) WITH ORDINALITY AS ord(attnum, ordinality)
        JOIN pg_attribute AS att
          ON att.attrelid = rec.conrelid
         AND att.attnum = ord.attnum;

        IF rec.table_name = 'test_column'
           AND (
                cols = ARRAY['test_profile_id', 'column_key']::text[]
                OR cols = ARRAY['test_profile_id', 'column_order']::text[]
           ) THEN
            EXECUTE format('ALTER TABLE public.test_column DROP CONSTRAINT %I', rec.conname);
            RAISE NOTICE 'dropped unique % on test_column %', rec.conname, cols;
        ELSIF rec.table_name = 'test_point'
           AND cols = ARRAY['test_profile_id', 'point_order']::text[] THEN
            EXECUTE format('ALTER TABLE public.test_point DROP CONSTRAINT %I', rec.conname);
            RAISE NOTICE 'dropped unique % on test_point %', rec.conname, cols;
        END IF;
    END LOOP;
END;
$drop_profile_scoped_uniques$;

