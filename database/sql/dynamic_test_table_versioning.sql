CREATE FUNCTION public.test_profile_version_assert_draft(version_id bigint)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
DECLARE
    version_status text;
BEGIN
    SELECT status
    INTO version_status
    FROM public.test_profile_version
    WHERE test_profile_version_id = version_id
    FOR NO KEY UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'test profile version % does not exist', version_id
            USING ERRCODE = '23503', CONSTRAINT = 'fk_test_column_version_profile';
    END IF;

    IF version_status IS DISTINCT FROM 'draft' THEN
        RAISE EXCEPTION 'published test table versions cannot be edited'
            USING ERRCODE = '23514', CONSTRAINT = 'test_profile_version_immutable';
    END IF;
END;
$$;

CREATE FUNCTION public.test_profile_version_draft_id(profile_id bigint)
RETURNS bigint
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
DECLARE
    version_id bigint;
BEGIN
    SELECT test_profile_version_id
    INTO version_id
