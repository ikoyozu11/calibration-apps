INSERT INTO public.test_profile_version (
    test_profile_id,
    version_number,
    status,
    profile_name,
    display_title,
    description,
    published_at,
    created_at
)
SELECT
    profile_row.test_profile_id,
    1,
    CASE
        WHEN public.test_profile_is_used_in_calibration(profile_row.test_profile_id) THEN 'active'
        ELSE 'draft'
    END,
    profile_row.profile_name,
    profile_row.display_title,
    profile_row.description,
    CASE
        WHEN public.test_profile_is_used_in_calibration(profile_row.test_profile_id)
            THEN COALESCE(profile_row.created_at, now())
        ELSE NULL
    END,
    COALESCE(profile_row.created_at, now())
FROM public.test_profile AS profile_row
WHERE NOT EXISTS (
    SELECT 1
    FROM public.test_profile_version AS version_row
    WHERE version_row.test_profile_id = profile_row.test_profile_id
      AND version_row.version_number = 1
);

UPDATE public.test_column AS column_row
SET test_profile_version_id = version_row.test_profile_version_id
FROM public.test_profile_version AS version_row
WHERE version_row.test_profile_id = column_row.test_profile_id
  AND version_row.version_number = 1
  AND column_row.test_profile_version_id IS NULL;

UPDATE public.test_point AS point_row
SET test_profile_version_id = version_row.test_profile_version_id
FROM public.test_profile_version AS version_row
WHERE version_row.test_profile_id = point_row.test_profile_id
  AND version_row.version_number = 1
  AND point_row.test_profile_version_id IS NULL;

UPDATE public.test_point_value AS cell
SET test_profile_version_id = version_row.test_profile_version_id
FROM public.test_profile_version AS version_row
WHERE version_row.test_profile_id = cell.test_profile_id
  AND version_row.version_number = 1
  AND cell.test_profile_version_id IS NULL;

DO $backfill_guard$
DECLARE
    missing integer;
BEGIN
    SELECT count(*) INTO missing
    FROM public.test_profile AS profile_row
    WHERE NOT EXISTS (
        SELECT 1
        FROM public.test_profile_version AS version_row
        WHERE version_row.test_profile_id = profile_row.test_profile_id
          AND version_row.version_number = 1
          AND version_row.status = CASE
              WHEN public.test_profile_is_used_in_calibration(profile_row.test_profile_id) THEN 'active'
              ELSE 'draft'
          END
    );

    IF missing <> 0 THEN
        RAISE EXCEPTION 'version 1 backfill missed % unused-draft or used-active test_profile row(s)', missing;
    END IF;

    SELECT count(*) INTO missing
    FROM public.test_column
    WHERE test_profile_version_id IS NULL;

    IF missing <> 0 THEN
        RAISE EXCEPTION 'version 1 backfill left % test_column row(s) without a version', missing;
    END IF;

    SELECT count(*) INTO missing
    FROM public.test_point
    WHERE test_profile_version_id IS NULL;

    IF missing <> 0 THEN
        RAISE EXCEPTION 'version 1 backfill left % test_point row(s) without a version', missing;
    END IF;

    SELECT count(*) INTO missing
    FROM public.test_point_value
    WHERE test_profile_version_id IS NULL;

    IF missing <> 0 THEN
        RAISE EXCEPTION 'version 1 backfill left % test_point_value row(s) without a version', missing;
    END IF;
END;
$backfill_guard$;

