CREATE FUNCTION public.trg_calibration_scope_version_match()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
DECLARE
    version_profile_id bigint;
BEGIN
    IF NEW.test_profile_version_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT test_profile_id
    INTO version_profile_id
    FROM public.test_profile_version
    WHERE test_profile_version_id = NEW.test_profile_version_id;

    IF NOT FOUND THEN
        RETURN NEW;
    END IF;

    IF NEW.test_profile_id IS DISTINCT FROM version_profile_id THEN
        RAISE EXCEPTION 'calibration scope profile does not match the pinned version'
            USING ERRCODE = '23514', CONSTRAINT = 'calibration_scope_version_profile';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_calibration_scope_version_match ON public.calibration_scope;

CREATE TRIGGER trg_calibration_scope_version_match
BEFORE INSERT OR UPDATE OF test_profile_id, test_profile_version_id
ON public.calibration_scope
FOR EACH ROW
EXECUTE FUNCTION public.trg_calibration_scope_version_match();

