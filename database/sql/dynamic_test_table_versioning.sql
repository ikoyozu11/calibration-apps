CREATE TABLE public.test_profile_version (
    test_profile_version_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_profile_id bigint NOT NULL,
    version_number integer NOT NULL,
    status text NOT NULL,
    profile_name varchar(150) NOT NULL,
    display_title varchar(255),
    description text,
    published_at timestamp without time zone,
    created_at timestamp without time zone NOT NULL DEFAULT now(),
    CONSTRAINT uq_test_profile_version_number
        UNIQUE (test_profile_id, version_number),
    CONSTRAINT uq_test_profile_version_identity
        UNIQUE (test_profile_id, test_profile_version_id),
    CONSTRAINT fk_test_profile_version_profile
        FOREIGN KEY (test_profile_id)
        REFERENCES public.test_profile (test_profile_id)
        ON DELETE CASCADE,
    CONSTRAINT ck_test_profile_version_number
        CHECK (version_number >= 1),
    CONSTRAINT ck_test_profile_version_status
        CHECK (status IN ('draft', 'active', 'retired')),
    CONSTRAINT ck_test_profile_version_published
        CHECK (
            (status = 'draft' AND published_at IS NULL)
            OR (status IN ('active', 'retired') AND published_at IS NOT NULL)
        ),
    CONSTRAINT ck_test_profile_version_name
        CHECK (length(btrim(profile_name)) > 0)
);

CREATE UNIQUE INDEX uq_test_profile_version_active
    ON public.test_profile_version (test_profile_id)
    WHERE status = 'active';

CREATE UNIQUE INDEX uq_test_profile_version_draft
    ON public.test_profile_version (test_profile_id)
    WHERE status = 'draft';

CREATE INDEX ix_test_profile_version_profile
    ON public.test_profile_version (test_profile_id, status);

ALTER TABLE public.test_profile
    ADD COLUMN IF NOT EXISTS archived_at timestamp without time zone;

CREATE FUNCTION public.test_profile_is_used_in_calibration(p_test_profile_id bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SET search_path = pg_catalog
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.calibration_scope AS scope_row
        WHERE scope_row.test_profile_id = p_test_profile_id
    )
    OR EXISTS (
        SELECT 1
        FROM public.calibration_test_result AS result_row
        JOIN public.test_point AS point_row
          ON point_row.test_point_id = result_row.test_point_id
        WHERE point_row.test_profile_id = p_test_profile_id
    );
$$;

