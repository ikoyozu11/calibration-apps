CREATE FUNCTION public.trg_test_profile_version_immutable_row()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
DECLARE
    version_status text;
    version_id bigint;
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF TG_TABLE_NAME = 'test_profile_version' THEN
            version_id := OLD.test_profile_version_id;
            version_status := OLD.status;
        ELSE
            version_id := OLD.test_profile_version_id;

            SELECT status
            INTO version_status
            FROM public.test_profile_version
            WHERE test_profile_version_id = version_id;
        END IF;

        IF version_status IS DISTINCT FROM 'draft'
           AND public.test_profile_version_is_historically_referenced(version_id) THEN
            RAISE EXCEPTION 'published test table versions cannot be deleted'
                USING ERRCODE = '23514', CONSTRAINT = 'test_profile_version_immutable';
        END IF;

        RETURN OLD;
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF TG_TABLE_NAME = 'test_profile_version' THEN
            version_id := NEW.test_profile_version_id;
            version_status := NEW.status;
        ELSE
            version_id := NEW.test_profile_version_id;

            SELECT status
            INTO version_status
            FROM public.test_profile_version
            WHERE test_profile_version_id = version_id;
        END IF;

        IF version_status IS DISTINCT FROM 'draft' THEN
            RAISE EXCEPTION 'published test table versions cannot be edited'
                USING ERRCODE = '23514', CONSTRAINT = 'test_profile_version_immutable';
        END IF;

        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF TG_TABLE_NAME = 'test_profile_version' THEN
            version_id := OLD.test_profile_version_id;
            version_status := OLD.status;
        ELSE
            version_id := OLD.test_profile_version_id;

            SELECT status
            INTO version_status
            FROM public.test_profile_version
            WHERE test_profile_version_id = version_id;
        END IF;

        IF version_status IS DISTINCT FROM 'draft' THEN
            IF TG_TABLE_NAME = 'test_profile_version' THEN
                IF NEW.test_profile_id IS DISTINCT FROM OLD.test_profile_id
                   OR NEW.version_number IS DISTINCT FROM OLD.version_number
                   OR NEW.profile_name IS DISTINCT FROM OLD.profile_name
                   OR NEW.display_title IS DISTINCT FROM OLD.display_title
                   OR NEW.description IS DISTINCT FROM OLD.description
                   OR NEW.published_at IS DISTINCT FROM OLD.published_at THEN
                    RAISE EXCEPTION 'published test table versions cannot be edited'
                        USING ERRCODE = '23514', CONSTRAINT = 'test_profile_version_immutable';
                END IF;
            ELSE
                RAISE EXCEPTION 'published test table versions cannot be edited'
                    USING ERRCODE = '23514', CONSTRAINT = 'test_profile_version_immutable';
            END IF;
        END IF;

        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'version immutability trigger called for %', TG_OP
        USING ERRCODE = '0A000';
END;
$$;

