-- Additive Standard(s) Used configuration (Phase 1).
-- PostgreSQL 18. Apply ONLY to calibration_staging_db.
--
-- NOT IDEMPOTENT. Run exactly once.
-- Refuses to run when current_database() is not calibration_staging_db.
-- Does not INSERT assignment, instrument, or calibration rows.
-- Does not ALTER calibration_standard_usage.
--
-- Do not execute on calibration_db until staging tests pass.

BEGIN;

DO $guard$
BEGIN
    IF current_database() IS DISTINCT FROM 'calibration_staging_db' THEN
        RAISE EXCEPTION
            'refusing instrument_type_standard_assignment.sql: current_database()=%',
            current_database()
            USING ERRCODE = '42501';
    END IF;

    IF to_regclass('public.instrument_type_standard_assignment') IS NOT NULL THEN
        RAISE EXCEPTION
            'instrument_type_standard_assignment.sql is not idempotent and has already been applied'
            USING ERRCODE = '42710';
    END IF;
END;
$guard$;

CREATE TABLE public.instrument_type_standard_assignment (
    instrument_type_standard_assignment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_type_id bigint NOT NULL,
    standard_instrument_id bigint NOT NULL,
    assignment_order integer NOT NULL,
    default_range character varying(150),
    default_unit character varying(50),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_instrument_type_standard_assignment_order
        CHECK (assignment_order > 0),
    CONSTRAINT uq_instrument_type_standard_assignment
        UNIQUE (instrument_type_id, standard_instrument_id),
    CONSTRAINT uq_instrument_type_standard_assignment_order
        UNIQUE (instrument_type_id, assignment_order),
    CONSTRAINT fk_instrument_type_standard_assignment_type
        FOREIGN KEY (instrument_type_id)
        REFERENCES public.instrument_type (instrument_type_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_instrument_type_standard_assignment_instrument
        FOREIGN KEY (standard_instrument_id)
        REFERENCES public.instrument (instrument_id)
);

CREATE INDEX ix_instrument_type_standard_assignment_instrument
    ON public.instrument_type_standard_assignment (standard_instrument_id);

CREATE FUNCTION public.instrument_type_standard_assignment_reject_self()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.instrument_type AS instrument_type
        WHERE instrument_type.instrument_type_id = NEW.instrument_type_id
            AND instrument_type.instrument_id = NEW.standard_instrument_id
    ) THEN
        RAISE EXCEPTION 'an instrument cannot be assigned as its own standard'
            USING ERRCODE = '23514',
                CONSTRAINT = 'chk_instrument_type_standard_assignment_not_self';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_instrument_type_standard_assignment_reject_self
    BEFORE INSERT OR UPDATE OF instrument_type_id, standard_instrument_id
    ON public.instrument_type_standard_assignment
    FOR EACH ROW
    EXECUTE FUNCTION public.instrument_type_standard_assignment_reject_self();

COMMIT;
