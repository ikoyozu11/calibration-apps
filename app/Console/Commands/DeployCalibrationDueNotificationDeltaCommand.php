<?php

namespace App\Console\Commands;

use App\StagingSqlDeployment\ApprovedStagingSqlArtifacts;
use App\StagingSqlDeployment\DeltaAtomicStagingSqlPackageBuilder;
use App\StagingSqlDeployment\DeltaStagingSqlExecutionAdapter;
use App\StagingSqlDeployment\DeltaStagingSqlReleaseManifest;
use App\StagingSqlDeployment\PdoStagingSqlConnectionFactory;
use App\StagingSqlDeployment\ProcessGitRevisionReader;
use App\StagingSqlDeployment\StagingSqlDeploymentAuthorization;
use App\StagingSqlDeployment\StagingSqlDeploymentException;
use App\StagingSqlDeployment\StagingSqlDeploymentTarget;
use App\StagingSqlDeployment\StagingSqlExecutionOutcome;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Throwable;

/**
 * Controlled one-artifact staging delta deployment.
 *
 * The approval manifest is supplied by the release process, not generated by
 * this command. The command never accepts an arbitrary SQL path.
 */
#[Signature('staging:deploy-calibration-due-delta
    {--approval-manifest= : Absolute path to the approved external JSON manifest}
    {--backup-file= : Fresh custom-format staging backup whose hash is approved}
    {--confirm-database= : Must be exactly calibration_staging_db}
    {--confirm-host= : Must be exactly 127.0.0.1}
    {--confirm-port= : Must be exactly 5432}
    {--fresh-schema-inventory= : Must be exactly VERIFIED}
    {--fresh-trigger-fingerprint= : Must be exactly VERIFIED}
    {--confirm-execution= : Must be exactly CONFIRMED}
    {--i-authorize-staging-write= : Must be exactly AUTHORIZED}')]
#[Description('Atomically apply only the approved Calibration Due notification SQL delta to staging.')]
class DeployCalibrationDueNotificationDeltaCommand extends Command
{
    public function handle(): int
    {
        $factory = new PdoStagingSqlConnectionFactory;

        try {
            $this->assertOptionExact('confirm-database', ApprovedStagingSqlArtifacts::APPROVED_DATABASE);
            $this->assertOptionExact('confirm-host', '127.0.0.1');
            $this->assertOptionExact('confirm-port', (string) ApprovedStagingSqlArtifacts::APPROVED_PORT);
            $this->assertOptionExact('fresh-schema-inventory', 'VERIFIED');
            $this->assertOptionExact('fresh-trigger-fingerprint', 'VERIFIED');
            $this->assertOptionExact('confirm-execution', 'CONFIRMED');
            $this->assertOptionExact('i-authorize-staging-write', 'AUTHORIZED');

            $manifestPath = (string) $this->option('approval-manifest');
            $backupPath = (string) $this->option('backup-file');
            if ($manifestPath === '' || $backupPath === '') {
                throw new StagingSqlDeploymentException('Approval manifest and fresh backup file are required.');
            }

            $approval = DeltaStagingSqlReleaseManifest::approvalFromFile($manifestPath);
            $this->assertConfiguredStagingConnection();
            $this->assertFreshBackup($backupPath, $approval->freshBackupSha256);

            $package = (new DeltaAtomicStagingSqlPackageBuilder(
                repositoryRoot: base_path(),
                gitRevisionReader: new ProcessGitRevisionReader(base_path()),
                approval: $approval,
            ))->build();

            $authorization = new StagingSqlDeploymentAuthorization(
                operatorWriteApproved: true,
                backupBaselineVerified: true,
                freshSchemaInventoryVerified: true,
                freshTriggerFingerprintVerified: true,
                operatorConfirmedExecution: true,
                approvedBackupSha256: $approval->freshBackupSha256,
                approvedCheckpoint: $approval->checkpoint,
                approvedDatabase: ApprovedStagingSqlArtifacts::APPROVED_DATABASE,
                approvedHost: '127.0.0.1',
                approvedPort: ApprovedStagingSqlArtifacts::APPROVED_PORT,
                approvedReleaseHead: $approval->approvedHead,
                approvedArtifactSha256: [$approval->artifactSha256],
            );

            $staging = config('database.connections.pgsql_staging');
            $factory->unsealForApprovedDelta(
                $approval,
                (string) $staging['username'],
                (string) $staging['password'],
            );

            $outcome = (new DeltaStagingSqlExecutionAdapter($factory))->execute(
                package: $package,
                approval: $approval,
                target: StagingSqlDeploymentTarget::approvedLocalStaging(),
                authorization: $authorization,
            );

            $this->line('status: '.$outcome->status);
            $this->line('committed: '.($outcome->committed ? 'yes' : 'no'));
            $this->line('opened_postgresql: '.($outcome->openedPostgreSql ? 'yes' : 'no'));
            $this->line($outcome->message);

            return $outcome->status === StagingSqlExecutionOutcome::STATUS_COMMITTED
                ? self::SUCCESS
                : self::FAILURE;
        } catch (Throwable $exception) {
            $this->error($exception->getMessage());

            return self::FAILURE;
        } finally {
            $factory->reseal();
        }
    }

    private function assertConfiguredStagingConnection(): void
    {
        $staging = config('database.connections.pgsql_staging');
        if (! is_array($staging)
            || ($staging['database'] ?? null) !== ApprovedStagingSqlArtifacts::APPROVED_DATABASE
            || ! in_array(strtolower((string) ($staging['host'] ?? '')), ApprovedStagingSqlArtifacts::APPROVED_HOSTS, true)
            || (string) ($staging['port'] ?? '') !== (string) ApprovedStagingSqlArtifacts::APPROVED_PORT
            || ($staging['url'] ?? null) !== null) {
            throw new StagingSqlDeploymentException('pgsql_staging config is not the approved staging endpoint.');
        }

        if ((string) ($staging['username'] ?? '') === '') {
            throw new StagingSqlDeploymentException('Staging SQL username is required.');
        }
    }

    private function assertFreshBackup(string $path, string $expectedHash): void
    {
        if (! is_file($path) || ! is_readable($path) || (filesize($path) ?: 0) === 0) {
            throw new StagingSqlDeploymentException('Fresh staging backup is missing, unreadable, or empty.');
        }

        $actualHash = hash_file('sha256', $path);
        if ($actualHash === false || ! hash_equals(strtolower($expectedHash), strtolower($actualHash))) {
            throw new StagingSqlDeploymentException('Fresh staging backup SHA-256 mismatch.');
        }
    }

    private function assertOptionExact(string $option, string $expected): void
    {
        if ((string) $this->option($option) !== $expected) {
            throw new StagingSqlDeploymentException("Authorization option [--{$option}] mismatch.");
        }
    }
}
